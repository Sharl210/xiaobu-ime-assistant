#!/usr/bin/env bash
# 从凭据保险箱取出一条的明文（仅打印正文，不含标识行）。
# 用法: tools/vault-get.sh "<条目标识>"
set -euo pipefail

V="$HOME/AgentsBook/vault"
SALT=$((1700000000+32984557))

# 参数表（m0/a0，24 行）
M0=(1250495 1328397 1074760 1519164 1378904 1326088 1194028 1306704 1007402 1368302 1205810 1529001 \
    1546030 1296091 1448482 1444499 1057533 1424386 1133948 1331891 1192472 1144647 1137794 1110686)
A0=(361194364 164672004 141616624 317151836 157351270 138005596 349965171 236393770 171566145 389074981 106555540 176487109 \
    137615837 209823580 160415404 163306626 119090339 119988298 239066141 115345966 364824958 414890006 169795202 215549745)

ID="${1:?需要条目标识}"
NAME=$(printf '%s' "$ID$SALT" | sha256sum | cut -c1-16)
R=$(head -n1 -- "$V/$NAME")

d1=${R:2:1}; d2=${R:6:1}; d3=${R:10:1}
t() { case "$1" in 0) echo 4;; 1) echo 7;; 2) echo 2;; 3) echo 9;; 4) echo 6;; \
  5) echo 1;; 6) echo 8;; 7) echo 0;; 8) echo 3;; 9) echo 5;; esac; }
e1=$(t "$d1"); e2=$(t "$d2"); e3=$(t "$d3")
K=$(( (e1 + 2*e2 + 4*e3) % 24 ))
U=$(( 100*e1 + 10*e2 + e3 ))
M=$(( ${M0[$K]} + U ))
A=$(( ${A0[$K]} + 10000*U ))

awk -v m="$M" -v a="$A" 'NR==1{s=$1%4294967296;next}{for(i=1;i<=NF;i++){s=(m*s+a)%4294967296;printf "%c",($i-int(s/65536)%256+256)%256}}' "$V/$NAME" | tail -n +2
